def add(a, b):
    """
    Add two numeric values and return their sum.
    
    Args:
        a: First numeric value
        b: Second numeric value
    
    Returns:
        The sum of a and b
    """
    return a + b


def multiply(a, b):
    """
    Multiply two numeric values and return their product.
    
    Args:
        a: First numeric value
        b: Second numeric value
    
    Returns:
        The product of a and b
    """
    return a * b
